)
SELECT
    src.transaction_id,
    s.store_id,
    src.transaction_date::date,
    c.cashier_surr_id,
    cu.customer_surr_id,
    src.items_count::smallint,
    src.total_amount_ngn::numeric,
    src.discount_applied::boolean,
    src.loyalty_points_earned::int,
