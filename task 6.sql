JOIN bl_3nf.ce_store s
    ON s.store_name = src.store_name
JOIN bl_3nf.ce_city ci
    ON ci.city_id = s.city_id
   AND ci.city_name = src.city
JOIN bl_3nf.ce_cashier c
    ON c.cashier_src_id = src.cashier_id
JOIN bl_3nf.ce_customer cu
    ON cu.customer_src_id = src.customer_id
JOIN bl_3nf.ce_payment_method pm
    ON pm.payment_method_name = src.payment_method
JOIN bl_3nf.ce_source so
    ON so.source_entity = 'src_source1'
ON CONFLICT (transaction_src_id, source_id) DO NOTHING;
